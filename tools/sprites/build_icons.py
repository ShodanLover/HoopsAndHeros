"""One command to rebuild the 16x16 UI icons with agent-sprite-forge codeart2d.

  python tools/sprites/build_icons.py

1. Regenerates art/sprites/icons/icons.pixelspec.json (tools/sprites/icon_spec.py).
2. Renders it with codeart2d render_pixelspec.py --strict-qc into art/sprites/icons/build/.
3. Packs every icon into crisp two-tone SVG paths in js/icon-data.js. Both tones use currentColor
   (the second at reduced opacity), so icons keep the color of the button they sit in.
"""
import json, os, shutil, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import icon_spec as I  # noqa: E402
from build_player import forge_dir, run, ROOT  # noqa: E402

ART = os.path.join(ROOT, 'art', 'sprites', 'icons')
BUILD = os.path.join(ART, 'build')
OUT = os.path.join(ROOT, 'js', 'icon-data.js')


def hex_rgb(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def runs_path(grid, ch):
    d = []
    for y, row in enumerate(grid):
        x = 0
        while x < len(row):
            if row[x] == ch:
                x0 = x
                while x < len(row) and row[x] == ch:
                    x += 1
                d.append('M%d %dh%dv1h-%dz' % (x0, y, x - x0, x - x0))
            else:
                x += 1
    return ''.join(d)


def pack():
    meta = json.load(open(os.path.join(BUILD, 'codeart-meta.json'), encoding='utf8'))
    lut = {hex_rgb(v): k for k, v in I.PALETTE.items()}
    icons = {}
    for o in meta['outputs']:
        path = o['path']
        if '/frames/' not in path or not path.endswith('.png'):
            continue
        name = os.path.basename(path)[:-4]
        im = Image.open(os.path.join(BUILD, path)).convert('RGBA')
        px = im.load()
        grid = []
        for y in range(1, I.N + 1):
            row = ''
            for x in range(1, I.N + 1):
                r, g, b, a = px[x, y]
                row += lut[(r, g, b)] if a else '.'
            grid.append(row)
        icons[name] = [runs_path(grid, 'x'), runs_path(grid, 'o')]
    # codeart2d stores frames with identical pixels once (aliases such as recruit = cards): copy them over
    for n in I.ICONS:
        if n not in icons:
            twin = next((k for k in icons if I.ICONS[k] == I.ICONS[n]), None)
            if twin is None:
                sys.exit('no rendered frame for icon ' + n)
            icons[n] = icons[twin]
    js = ('/* GENERATED by tools/sprites/build_icons.py from agent-sprite-forge codeart2d renders of\n'
          ' * art/sprites/icons/icons.pixelspec.json (code-drawn, no image model). Do not edit by hand. */\n'
          '(function (root) {\n  \'use strict\';\n  const BE = (root.BE = root.BE || {});\n'
          '  BE.iconData = ' + json.dumps(icons, separators=(',', ':'), sort_keys=True) + ';\n'
          '})(typeof window !== \'undefined\' ? window : globalThis);\n')
    with open(OUT, 'w', encoding='utf8', newline='\n') as fh:
        fh.write(js)
    print('packed', len(icons), 'icons into js/icon-data.js', len(js) // 1024, 'KB')


def main():
    render = os.path.join(forge_dir(), 'skills', 'codeart2d', 'scripts', 'render_pixelspec.py')
    run([os.path.join(HERE, 'icon_spec.py')])
    if os.path.isdir(BUILD):
        shutil.rmtree(BUILD)
    run([render, '--spec', os.path.join(ART, 'icons.pixelspec.json'), '--output-dir', BUILD, '--preview-scale', '4', '--strict-qc'])
    pack()


if __name__ == '__main__':
    main()
