"""Packs the codeart2d-rendered player parts into js/sprite-data.js.

Reads art/sprites/player/build/parts/codeart-meta.json and its PNG frames, maps every pixel back to
its slot letter (the placeholder palette in player_spec.SLOTS), crops each part to its bounding box
and run-length encodes it. The runtime (js/sprites.js) recolors the slots per athlete.
"""
import json, os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import player_spec as P  # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
BUILD = os.path.join(ROOT, 'art', 'sprites', 'player', 'build', 'parts')
OUT = os.path.join(ROOT, 'js', 'sprite-data.js')


def hex_rgb(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def rle(s):
    out, i = [], 0
    while i < len(s):
        j = i
        while j < len(s) and s[j] == s[i]:
            j += 1
        n = j - i
        out.append((str(n) if n > 1 else '') + s[i])
        i = j
    return ''.join(out)


def main():
    meta = json.load(open(os.path.join(BUILD, 'codeart-meta.json'), encoding='utf8'))
    lut = {hex_rgb(v): k for k, v in P.SLOTS.items()}
    parts = {}
    for o in meta['outputs']:
        path = o['path']
        if not path.startswith('base/frames/') or not path.endswith('.png'):
            continue
        name = os.path.basename(path)[:-4]
        im = Image.open(os.path.join(BUILD, path)).convert('RGBA')
        w, h = im.size
        px = im.load()
        grid = [['.'] * w for _ in range(h)]
        for y in range(h):
            for x in range(w):
                r, g, b, a = px[x, y]
                if a == 0:
                    continue
                if (r, g, b) not in lut:
                    sys.exit('off-palette pixel %s at %d,%d in %s' % ((r, g, b), x, y, path))
                grid[y][x] = lut[(r, g, b)]
        ys = [y for y in range(h) if any(c != '.' for c in grid[y])]
        xs = [x for x in range(w) if any(grid[y][x] != '.' for y in range(h))]
        x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
        body = ''.join(''.join(grid[y][x0:x1 + 1]) for y in range(y0, y1 + 1))
        parts[name] = [x0, y0, x1 - x0 + 1, y1 - y0 + 1, rle(body)]
    data = {'w': P.W, 'h': P.H, 'anchor': [12, 34], 'parts': parts}
    js = ('/* GENERATED by tools/sprites/pack_player.py from agent-sprite-forge codeart2d renders of\n'
          ' * art/sprites/player/player-parts.pixelspec.json (code-drawn, no image model). Do not edit by hand. */\n'
          '(function (root) {\n  \'use strict\';\n  const BE = (root.BE = root.BE || {});\n  BE.spriteData = BE.spriteData || {};\n'
          '  BE.spriteData.player = ' + json.dumps(data, separators=(',', ':')) + ';\n'
          '})(typeof window !== \'undefined\' ? window : globalThis);\n')
    with open(OUT, 'w', encoding='utf8', newline='\n') as fh:
        fh.write(js)
    print('packed', len(parts), 'parts into js/sprite-data.js', len(js) // 1024, 'KB')


if __name__ == '__main__':
    main()
